DELIMITER//
CREATE FUNCTION GRADE(MARK INT)
RETURNS VARCHAR(15)
DETERMINISTIC
BEGIN 
	IF MARK>=70 THEN
		RETURN 'A';
	ELSEIF MARK>=50 THEN
		RETURN 'B';
	ELSEIF MARK>=30 THEN 
		RETURN 'C';
	ELSE 
		RETURN 'FAIL';
	END IF;
END//
DELIMITER //
SELECT GRADE(45);
    


