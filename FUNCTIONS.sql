#BUILD FUNCTION 
DELIMITER //
CREATE FUNCTION GETSQUARE(NUM INT)
RETURNS INT
DETERMINISTIC
BEGIN 
    RETURN NUM*NUM ;
END//
DELIMITER //
#CALLING FUNCTION
SELECT GETSQUARE(5);

#CREATING WITH TWO ARGUMENT
DELIMITER//
CREATE FUNCTION TOTALPRODUCT(PRICE DECIMAL(10,2),QUANTITY INT)
RETURNS INT
DETERMINISTIC
BEGIN
	RETURN PRICE*QUANTITY;
END//
DELIMITER //
#CALLING 
SELECT TOTALPRODUCT(50,3);

#CREATING INTEGIER FUNCTION
DELIMITER // 
CREATE FUNCTION FULL_NAME(FIRSTNAME VARCHAR(15),LASTNAME VARCHAR(15))
RETURNS VARCHAR(50)
DETERMINISTIC
BEGIN 
	RETURN CONCAT(FIRSTNAME,' ',LASTNAME);
END//
DELIMITER //
SELECT FULL_NAME('IBNU','MUHAJIR');
