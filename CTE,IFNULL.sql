USE IBNU;
SELECT * FROM EMPLOYEEDATA;
SELECT * FROM EMPLOYEEDATA WHERE DEPARTMENT='HR' AND SALARY>50000;
SELECT DEPARTMENT,AVG(SALARY) AS AVERAGE_SALARY FROM EMPLOYEEDATA GROUP BY DEPARTMENT HAVING AVG(SALARY)>50000;
#WITH CTE
WITH DEPARTMENT_SALARY AS(
	SELECT DEPARTMENT,AVG(SALARY) AS AVERAGE_SALARY FROM EMPLOYEEDATA GROUP BY DEPARTMENT)
SELECT * FROM DEPARTMENT_SALARY WHERE AVERAGE_SALARY>50000;
#CASE 
SELECT NAME,SALARY,
		CASE
			WHEN SALARY >=60000 THEN 'HIGH'
            WHEN SALARY>=50000 THEN 'MEDIUM'
            ELSE 'LOW'
		END AS SALARY_LEVEL
FROM EMPLOYEEDATA;
#IFNULL
UPDATE EMPLOYEEDATA SET EMAIL='' = NULLIF(EMAIL,'') WHERE EMAIL='';
UPDATE EMPLOYEEDATA SET EMAIL= NULL WHERE EMAIL='';
SELECT NAME,EMAIL,IFNULL(EMAIL,'UNKNOWN') AS CHANGED_EMAIL FROM EMPLOYEEDATA;
#IFNULL FUNCTION 
SELECT NAME,EMAIL,IFNULL(EMAIL,(SELECT AVG(SALARY) FROM EMPLOYEEDATA)) AS EMAIL_LENGTH FROM EMPLOYEEDATA;
SELECT NAME,EMAIL,COALESCE(EMAIL,NAME,'NO WORDS') AS CONTACT_NUMBER FROM EMPLOYEEDATA;



