# CREATE DATABASE
CREATE DATABASE STUDENT;
USE STUDENT;
#CREATING TABLE
CREATE TABLE STUDENT_DETAILS(STUDENT_ID INT,STUDENT_NAME VARCHAR(10),STUDENT_MARK INT);
#SEE THE TABLE
SELECT * FROM STUDENT_DETAILS;
#ADD COLUMN 
ALTER TABLE STUDENT_DETAILS ADD ADDRESS VARCHAR(10);
#RENAME TABLE
RENAME TABLE STUDENT_DETAILS TO STUDENTS;
SELECT * FROM STUDENTS;
#DELETE ENTIRE TABLE
DROP TABLE STUDENTS;
#CREATING NEW DATABASE
CREATE DATABASE EMPLOYEES;
