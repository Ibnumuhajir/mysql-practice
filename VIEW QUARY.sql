#TRIGGER AFTER UPDATE 
CREATE TABLE SALARY_LOG(EMP_ID INT PRIMARY KEY,OLD_SALARY INT ,NEW_SALARY INT);
DELIMITER //
CREATE TRIGGER SALARY_UPDATE_LOG AFTER UPDATE ON EMP FOR EACH ROW 
BEGIN 
	INSERT INTO SALARY_LOG VALUES(OLD.ID,OLD.SALARY,NEW.SALARY);
END//
DELIMITER ; 
UPDATE EMP SET SALARY=60000 WHERE ID=101;
