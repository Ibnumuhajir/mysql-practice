CREATE TABLE EMP(ID INT PRIMARY KEY,NAME VARCHAR(50),SALARY INT );
CREATE TABLE EMP_LOG(EMP_ID INT,EMP_NAME VARCHAR(50),ACTION VARCHAR(50));
DELIMITER //
CREATE TRIGGER AFTER_EMP_INSERT AFTER INSERT ON EMP FOR EACH ROW
BEGIN
	INSERT INTO EMP_LOG VALUES(NEW.ID,NEW.NAME,'EMPLOYEE ADDED');
END//
DELIMITER ;

